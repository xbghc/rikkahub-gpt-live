package me.rerere.rikkahub.service

import kotlinx.coroutines.CompletableDeferred
import kotlinx.coroutines.CoroutineStart
import kotlinx.coroutines.NonCancellable
import kotlinx.coroutines.awaitCancellation
import kotlinx.coroutines.launch
import kotlinx.coroutines.test.runCurrent
import kotlinx.coroutines.test.runTest
import kotlinx.coroutines.withContext
import me.rerere.ai.core.MessageRole
import me.rerere.ai.ui.ToolApprovalState
import me.rerere.ai.ui.UIMessage
import me.rerere.ai.ui.UIMessagePart
import me.rerere.rikkahub.data.model.Conversation
import me.rerere.rikkahub.data.model.MessageNode
import me.rerere.rikkahub.data.model.toMessageNode
import me.rerere.rikkahub.data.model.withToolApproval
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertSame
import org.junit.Assert.assertTrue
import org.junit.Test
import kotlin.uuid.Uuid

class LiveChatTaskTest {
    @Test
    fun `late cleanup leaves ordinary and other live owners approvals pending`() = runTest {
        val user = UIMessage.user("Live request")
        val owned = pendingTool("owned")
        val ordinary = pendingTool("ordinary")
        val otherLive = pendingTool("other-live")
        val task = taskFor(user, owned)
        var conversation = conversation(user, owned)
        val allowCompletion = CompletableDeferred<Unit>()
        val job = launch(start = CoroutineStart.UNDISPATCHED) {
            try {
                awaitCancellation()
            } finally {
                withContext(NonCancellable) { allowCompletion.await() }
            }
        }
        task.job = job
        job.invokeOnCompletion { cause ->
            val cancelled = cause as LiveTaskCancellationException
            assertSame(task, cancelled.task)
            conversation = cancelled.task.cancelPendingTools(conversation, 3) ?: conversation
        }

        task.cancel()
        runCurrent()
        assertFalse(job.isCompleted)
        assertFalse(task.ownsToolApproval(conversation, 3, "owned"))
        // A different request can reach an approval while the cancelled job finishes saving.
        conversation = conversation.copy(messageNodes = conversation.messageNodes + listOf(
            UIMessage.user("Typed request").toMessageNode(),
            ordinary.toMessageNode(),
            UIMessage.user("Another Live request").toMessageNode(),
            otherLive.toMessageNode(),
        ))
        allowCompletion.complete(Unit)
        job.join()

        assertTrue(conversation.currentMessages.first { it.id == owned.id }.getTools().single().isExecuted)
        assertTrue(conversation.currentMessages.first { it.id == ordinary.id }.getTools().single().isPending)
        assertTrue(conversation.currentMessages.first { it.id == otherLive.id }.getTools().single().isPending)
        assertNull(task.cancelPendingTools(conversation, 3))
    }

    @Test
    fun `branch changes only cancel the message generated by the live task`() {
        val user = UIMessage.user("request")
        val owned = pendingTool("owned")
        val otherBranch = pendingTool("other-branch")
        val task = taskFor(user, owned)
        val conversation = conversation(user).copy(messageNodes = listOf(
            user.toMessageNode(),
            MessageNode(messages = listOf(owned, otherBranch), selectIndex = 1),
        ))

        assertFalse(task.isCurrent(conversation, 3))
        assertFalse(task.ownsToolApproval(conversation, 3, "other-branch"))
        val cleaned = task.cancelPendingTools(conversation, 3)!!
        assertSame(otherBranch, cleaned.currentMessages.last())
        assertEquals(1, cleaned.messageNodes.last().selectIndex)
        assertTrue(cleaned.messageNodes.last().messages.first().getTools().single().isExecuted)
        assertTrue(cleaned.currentMessages.last().getTools().single().isPending)
    }

    @Test
    fun `removing the live user message never transfers ownership to an adjacent request`() {
        val deletedUser = UIMessage.user("deleted")
        val owned = pendingTool("owned")
        val ordinary = pendingTool("ordinary")
        val task = taskFor(deletedUser, owned)
        val conversation = conversation(owned, UIMessage.user("typed"), ordinary)

        assertFalse(task.isCurrent(conversation, 3))
        val cleaned = task.cancelPendingTools(conversation, 3)!!
        assertTrue(cleaned.currentMessages.first().getTools().single().isExecuted)
        assertSame(ordinary, cleaned.currentMessages.last())
        assertTrue(ordinary.getTools().single().isPending)
    }

    @Test
    fun `delete and restore invalidate cleanup even when message ids are restored`() {
        val user = UIMessage.user("request")
        val owned = pendingTool("owned")
        val task = taskFor(user, owned)
        val restored = conversation(user, owned)

        assertFalse(task.isCurrent(restored, 4))
        assertNull(task.cancelPendingTools(restored, 4))
        assertTrue(restored.currentMessages.last().getTools().single().isPending)
    }

    @Test
    fun `revoking owned tools makes a late approval click harmless`() {
        val user = UIMessage.user("request")
        val owned = pendingTool("owned")
        val completed = pendingTool("completed").copy(parts = listOf(
            pendingTool("completed").getTools().single().copy(output = listOf(UIMessagePart.Text("already done")))
        ))
        val task = taskFor(user, owned).apply { recordAssistantMessage(completed.id) }
        val conversation = conversation(user, owned, completed)
        assertTrue(task.ownsToolApproval(conversation, 3, "owned"))

        task.cancel()
        val cleaned = task.cancelPendingTools(conversation, 3)!!
        assertNull(cleaned.withToolApproval("owned", ToolApprovalState.Approved))
        assertSame(completed, cleaned.currentMessages.last())
        assertFalse(task.ownsToolApproval(cleaned, 3, "owned"))
    }

    @Test
    fun `a queued task with no generated messages cannot cancel any tools`() {
        val pending = pendingTool("unrelated")
        val task = LiveChatTask("queued")
        task.cancel()
        assertNull(task.cancelPendingTools(conversation(pending), 3))
        assertTrue(pending.getTools().single().isPending)
    }

    private fun taskFor(user: UIMessage, assistant: UIMessage) = LiveChatTask("owner").apply {
        incarnation = 3
        userMessageId = user.id
        recordAssistantMessage(assistant.id)
    }

    private fun conversation(vararg messages: UIMessage) = Conversation(
        assistantId = Uuid.random(),
        messageNodes = messages.map { it.toMessageNode() },
    )

    private fun pendingTool(id: String) = UIMessage(
        role = MessageRole.ASSISTANT,
        parts = listOf(UIMessagePart.Tool(
            toolCallId = id,
            toolName = "workspace_shell",
            input = "{}",
            approvalState = ToolApprovalState.Pending,
        )),
    )
}
